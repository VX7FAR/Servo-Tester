void displaystats(String m,float pwm = 0.0,float pos = 0.0,float a = 0.0 ){
  if(m == "MANUAL"){
    display.setTextSize(1);
    display.println("MODE: " + m); 
    display.println("PULSE: " + String(pwm) + "ms");
    display.println("POT POSITION: " + String(pos));
    display.println("ANGLE: " + String(a));
  }
  else if(m == "SWEEP"){
    display.setTextSize(2);
    display.setCursor(0,0);
    display.println("SWEEP");
    display.println("SPEED:" + String(int(pwm)) + "%");
  }
  display.display();
}

float position = 0.0f;
bool mode_pressed = false;
bool old_mode = false;
bool reset_pressed = false;
servomode mode = manual;

float pot = 0.0f;
float range = 0.0f;
float min = 0;
float max = 1023;

size_t msdelay = 30;
float i = 5.55f;
float at = 0.0f;

void setup()
{
  Serial.begin(9600);
  pinMode(3, OUTPUT);
  pinMode(4, INPUT);
  digitalWrite(3, HIGH);

  pinMode(7, OUTPUT);
  pinMode(8, INPUT);
  digitalWrite(7, HIGH);

  pot = analogRead(0);
  range = max - min;

  if(!display.begin(SSD1306_SWITCHCAPVCC,OLED_ADDRESS)){
    while(true){ Serial.println("SCREEN NOT FOUND!");}
  }

  display.setTextWrap(false);
  display.setTextColor(SSD1306_WHITE);
  display.setCursor(0,0);
  display.setTextSize(4);
  
  const uint8_t* animation[] = {frame0, frame1, frame2, frame3, frame4, frame5, frame6, frame7, frame8, frame9, frame10, frame11};

  for(int i = 0;i < 12; i++){
    display.clearDisplay();
    display.drawBitmap(0,0,animation[i],128, 32, SSD1306_WHITE);
    display.display();
    delay(166);       // 2000ms / 12 frames
  }
}

void flipswitch(bool b, uint8_t pin)
{
  if (digitalRead(pin) == HIGH)
  {
    if (!b)
    {
      b = !b;
    }
    else
    {
      b = true;
    }
  }
  else
  {
    b = false;
  }
  delay(msdelay);
}

void loop()
{
  flipswitch(mode_pressed, 4);
  flipswitch(reset_pressed, 8);
  pot = (analogRead(0) - min) / range;
  display.clearDisplay();

  if(!mode_pressed){
    old_mode = false;
  }

  // Manages input
  if (mode_pressed && reset_pressed)
  {
    mode = calibration;
  }
  else if (mode_pressed && !old_mode)
  {
    if (mode == sweep)
    {
      mode = manual;
    }
    else if (mode == manual)
    {
      mode = sweep;
    }
  }
  else if (reset_pressed)
  {
    mode = centre;
  }

  // Manages Controlling of servos
  if (mode == calibration)
  {
    display.println("MODE: CALIBRATION");
    display.setTextWrap(true);
    display.setCursor(0,0);
    display.println("Move and keep at hightest position for 3 seconds \n");
    display.display();
    delay(3000);
    max = analogRead(0);
    display.clearDisplay();
    display.setCursor(0,0);
    display.println("MODE: CALIBRATION");
    display.println("Move and keep at lowest position for 3 seconds \n");
    display.display();
    delay(3000);
    min = analogRead(0);
    range = max - min;
    display.setCursor(0,0);
    display.println("MODE: CALIBRATION");
    display.println("Calibrated! \n");
    mode = manual;
  }
  else if (mode == manual)
  {
    digitalWrite(11, LOW);
    digitalWrite(11, HIGH);
    delayMicroseconds(1000 + (1000 * pot));
    digitalWrite(11, LOW);
  }
  else if (mode == sweep)
  {
    displaystats("SWEEP", pot * 100.0);
    at += i;
    if(at >= 1000){
      at = 1000;
      i *= -1;
    } else if(at <= 0){
      at = 0;
      i *= -1;
    }
    digitalWrite(11, LOW);
    digitalWrite(11, HIGH);
    delayMicroseconds(1000 + at);
    digitalWrite(11, LOW);
    delay(50 * (1 - pot));
  }
}